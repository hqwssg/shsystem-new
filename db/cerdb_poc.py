"""Run a small, non-destructive CERDB compatibility probe.

The probe uses a PostgreSQL-wire-compatible driver only when CERDB_DSN is set.
It creates and drops a uniquely named temporary schema, and emits JSON results.
"""
from __future__ import annotations

import json
import os
import sys
import uuid
from concurrent.futures import ThreadPoolExecutor


def main() -> int:
    dsn = os.environ.get("CERDB_DSN")
    if not dsn:
        print(json.dumps({"status": "not-run", "reason": "CERDB_DSN is not set"}, ensure_ascii=False))
        return 2
    try:
        import psycopg
    except ImportError:
        print(json.dumps({"status": "not-run", "reason": "install vendor-supported psycopg-compatible driver"}, ensure_ascii=False))
        return 2
    schema = "poc_" + uuid.uuid4().hex[:12]
    checks: dict[str, str] = {}
    try:
        with psycopg.connect(dsn, autocommit=True) as conn:
            with conn.cursor() as cur:
                cur.execute(f'CREATE SCHEMA "{schema}"')
                cur.execute(f'''CREATE TABLE "{schema}".compat_probe (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    name VARCHAR(80) NOT NULL, created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
                    payload JSONB)''')
                cur.execute(f'''INSERT INTO "{schema}".compat_probe(name, payload)
                    VALUES (%s, %s) RETURNING id''', ("中文", json.dumps({"ok": True})))
                row_id = cur.fetchone()[0]
                checks["insert_returning"] = "ok" if row_id else "failed"
                cur.execute(f'SELECT name, payload->>\'ok\' FROM "{schema}".compat_probe WHERE id=%s', (row_id,))
                name, flag = cur.fetchone()
                checks["中文_json"] = "ok" if name == "中文" and flag == "true" else "failed"
                cur.execute("SELECT 1")
                checks["connection"] = "ok" if cur.fetchone()[0] == 1 else "failed"
                with conn.transaction():
                    cur.execute(f'INSERT INTO "{schema}".compat_probe(name) VALUES (%s)', ("rollback",))
                    raise RuntimeError("rollback sentinel")
    except RuntimeError as exc:
        if str(exc) != "rollback sentinel":
            checks["transaction_rollback"] = "failed"
        else:
            checks["transaction_rollback"] = "ok"
    except Exception as exc:
        print(json.dumps({"status": "failed", "error": str(exc), "checks": checks}, ensure_ascii=False))
        return 1
    finally:
        try:
            with psycopg.connect(dsn, autocommit=True) as conn:
                conn.execute(f'DROP SCHEMA IF EXISTS "{schema}" CASCADE')
        except Exception:
            checks["cleanup"] = "failed"
    checks["concurrency"] = "manual-review-required"
    checks["backup_restore"] = "manual-vendor-command-required"
    status = "passed" if all(value == "ok" or value.endswith("required") for value in checks.values()) else "failed"
    print(json.dumps({"status": status, "checks": checks}, ensure_ascii=False, indent=2))
    return 0 if status == "passed" else 1


if __name__ == "__main__":
    raise SystemExit(main())
