"""Convert the project's MySQL DDL for the openGauss/CERDB compatibility mode.

The converter is deliberately conservative: it writes converted SQL and warnings,
and only executes SQL when --apply is explicitly supplied with a vendor-supported
PostgreSQL driver. It is not a replacement for the CERDB vendor migration tool.
"""
from __future__ import annotations

import argparse
import os
import re
from pathlib import Path
from typing import Iterable


def convert(text: str) -> tuple[str, list[str]]:
    warnings: list[str] = []
    original = text
    text = text.replace("\ufeff", "")
    text = re.sub(r"/\*!\d+\s+(.*?)\s*\*/", r"\1", text, flags=re.S)
    text = re.sub(r"`([^`]+)`", r'"\1"', text)
    text = re.sub(r"(?im)^\s*ENGINE\s*=\s*\w+\s*;?", "", text)
    text = re.sub(r"(?im)\s+DEFAULT\s+CHARSET\s*=\s*\w+", "", text)
    text = re.sub(r"(?im)\s+CHARSET\s*=\s*\w+", "", text)
    text = re.sub(r"(?im)\s+COLLATE\s*=\s*[\w_]+", "", text)
    text = re.sub(r"(?i)\bTINYINT\s*\(\s*1\s*\)", "BOOLEAN", text)
    text = re.sub(r"(?i)\bDATETIME(?:\s*\(\s*\d+\s*\))?", "TIMESTAMP", text)
    text = re.sub(r"(?i)\bDOUBLE\b", "DOUBLE PRECISION", text)
    text = re.sub(r"(?i)\bJSON\b", "JSONB", text)
    text = re.sub(r"(?i)\bUNSIGNED\b", "", text)
    text = re.sub(r"(?i)\bAUTO_INCREMENT\b", "GENERATED BY DEFAULT AS IDENTITY", text)
    text = re.sub(r"(?i)\bON\s+UPDATE\s+CURRENT_TIMESTAMP(?:\(\d+\))?", "", text)
    text = re.sub(r"(?i)\bIFNULL\s*\(", "COALESCE(", text)
    text = re.sub(r"(?i)\bUTC_TIMESTAMP\s*\(\s*\d*\s*\)", "CURRENT_TIMESTAMP", text)
    text = re.sub(r"(?i)\bUTC_TIMESTAMP\b", "CURRENT_TIMESTAMP", text)
    text = re.sub(r"(?i)\bNOW\s*\(\s*\)", "CURRENT_TIMESTAMP", text)
    text = re.sub(r"(?i)\bTRUE\b", "TRUE", text)
    text = re.sub(r"(?i)\bFALSE\b", "FALSE", text)
    text = re.sub(r"(?i)\bLIMIT\s+(\d+)\s*,\s*(\d+)", r"LIMIT \2 OFFSET \1", text)
    text = re.sub(r"(?i)\bINSERT\s+IGNORE\b", "INSERT", text)
    if re.search(r"(?i)ON\s+DUPLICATE\s+KEY", original):
        warnings.append("ON DUPLICATE KEY UPDATE requires a table-specific ON CONFLICT rewrite")
    if re.search(r"(?i)JSON_(UNQUOTE|EXTRACT|SET|CONTAINS)", original):
        warnings.append("MySQL JSON_* functions require manual JSONB operator review")
    if re.search(r"(?i)GET_LOCK|RELEASE_LOCK|DATE_ADD|IF\s*\(", original):
        warnings.append("MySQL locking/date/control functions require manual rewrite")
    if re.search(r"(?i)ENUM\s*\(", original):
        warnings.append("ENUM syntax requires a CERDB-compatible type or CHECK constraint")
    if "GENERATED BY DEFAULT AS IDENTITY" in text and re.search(r"(?i)PRIMARY KEY", text):
        warnings.append("Verify identity placement for each primary-key column in CERDB")
    return text, sorted(set(warnings))


def sql_files(source: Path) -> Iterable[Path]:
    if source.is_file():
        yield source
    else:
        yield from sorted(source.rglob("*.sql"))


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--input", type=Path, default=Path("sql"))
    parser.add_argument("--output", type=Path, default=Path("build/cerdb-sql"))
    parser.add_argument("--apply", action="store_true")
    parser.add_argument("--dry-run", action="store_true")
    args = parser.parse_args()
    if args.apply and args.dry_run:
        parser.error("--apply and --dry-run are mutually exclusive")
    args.output.mkdir(parents=True, exist_ok=True)
    all_warnings: list[str] = []
    generated: list[Path] = []
    for source in sql_files(args.input):
        converted, warnings = convert(source.read_text(encoding="utf-8-sig"))
        target = args.output / source.relative_to(args.input if args.input.is_dir() else source.parent)
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(converted, encoding="utf-8")
        generated.append(target)
        all_warnings.extend(f"{source}: {warning}" for warning in warnings)
    manifest = args.output / "MIGRATION-WARNINGS.txt"
    manifest.write_text("\n".join(all_warnings) + ("\n" if all_warnings else "No automatic conversion warnings.\n"), encoding="utf-8")
    print(f"generated={len(generated)} output={args.output}")
    print(f"warnings={len(all_warnings)} file={manifest}")
    if args.apply:
        try:
            import psycopg
        except ImportError as exc:
            raise SystemExit("--apply requires the vendor-supported psycopg-compatible driver") from exc
        dsn = os.environ.get("CERDB_DSN")
        if not dsn:
            raise SystemExit("--apply requires CERDB_DSN; no SQL was executed")
        with psycopg.connect(dsn) as conn:
            with conn.cursor() as cur:
                for path in generated:
                    cur.execute(path.read_text(encoding="utf-8"))
        print("apply=completed")
    else:
        print("apply=not-run (use --apply only after CERDB POC approval)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
