param([switch]$SkipBuild)

$ErrorActionPreference = 'Stop'
$Root = (Resolve-Path (Join-Path $PSScriptRoot '../..')).Path
$Stamp = Get-Date -Format 'yyyyMMdd-HHmmss'
$Name = "runtime-update-$Stamp"
$Destination = Join-Path $Root "deploy-package/$Name"
$ExistingFullPackage = Get-ChildItem (Join-Path $Root 'deploy-package/server-update-*-*') -Directory -ErrorAction SilentlyContinue |
    Sort-Object LastWriteTime -Descending | Select-Object -First 1
New-Item -ItemType Directory -Force -Path $Destination | Out-Null

if (-not $SkipBuild) {
    $Maven = Get-Command mvnd.exe -ErrorAction SilentlyContinue
    if (-not $Maven) { $Maven = Get-Command mvn.cmd -ErrorAction Stop }
    $Npm = Get-Command npm.cmd -ErrorAction Stop

    & $Maven.Source -pl ruoyi-admin -am package -DskipTests
    if ($LASTEXITCODE -ne 0) { throw 'Main backend build failed.' }
    Push-Location (Join-Path $Root 'tpfhs-9/backend')
    & $Maven.Source package -DskipTests
    $Code = $LASTEXITCODE
    Pop-Location
    if ($Code -ne 0) { throw 'Carbon model backend build failed.' }
    Push-Location (Join-Path $Root 'goview/go-view-serve-master')
    & $Maven.Source package -DskipTests
    $Code = $LASTEXITCODE
    Pop-Location
    if ($Code -ne 0) { throw 'GoView backend build failed.' }

    foreach ($Frontend in @('ruoyi-ui', 'tpfhs-9/frontend', 'goview/go-view-master-fetch')) {
        Push-Location (Join-Path $Root $Frontend)
        if ($Frontend -eq 'ruoyi-ui') { & $Npm.Source run build:prod }
        elseif ($Frontend -eq 'tpfhs-9/frontend') { & $Npm.Source run build:server }
        else { & $Npm.Source run build }
        $Code = $LASTEXITCODE
        Pop-Location
        if ($Code -ne 0) { throw "Frontend build failed: $Frontend" }
    }
}

function Copy-Payload($Source, $Target) {
    $SourcePath = Join-Path $Root $Source
    $TargetPath = Join-Path $Destination $Target
    if (-not (Test-Path -LiteralPath $SourcePath)) { throw "Missing artifact: $SourcePath" }
    if ((Get-Item -LiteralPath $SourcePath).PSIsContainer) {
        New-Item -ItemType Directory -Force -Path $TargetPath | Out-Null
        Get-ChildItem -LiteralPath $SourcePath -Force | Copy-Item -Destination $TargetPath -Recurse -Force
    } else {
        New-Item -ItemType Directory -Force -Path (Split-Path $TargetPath -Parent) | Out-Null
        Copy-Item -LiteralPath $SourcePath -Destination $TargetPath -Force
    }
}

Copy-Payload 'ruoyi-admin/target/ruoyi-admin.jar' 'web-main/jar/ruoyi-admin.jar'
Copy-Payload 'tpfhs-9/backend/target/carbon-emission-model-1.0.0.jar' 'web-main/jar/carbon-emission-model.jar'
Copy-Payload 'goview/go-view-serve-master/target/goview_admin-0.0.1-SNAPSHOT.war' 'web-screen/jar/goview.war'
Copy-Payload 'ruoyi-ui/dist' 'web-main/html/dist'
Copy-Payload 'tpfhs-9/frontend/dist' 'web-main/html/carbon-model'
Copy-Payload 'goview/go-view-master-fetch/dist' 'web-screen/html/dist'
Copy-Payload 'energy_recovery_agent' 'web-main/energy-engine'
Copy-Payload 'carbon_report_agent' 'web-main/renderer/carbon_report_agent'
Copy-Payload 'single_train_recovery_agent' 'web-main/single-train-engine'
Copy-Payload 'new_function/single_train_energy_optimization-f6d1797' 'web-main/single-train-algorithm'
Copy-Payload 'tpfhs-9/backend/steam_calculator.py' 'web-main/python/steam_calculator.py'
Copy-Payload 'docker/web-main/requirements-cli.txt' 'web-main/requirements-cli.txt'
Copy-Payload 'tools/server-update/runtime-common.sh' 'scripts/runtime-common.sh'
Copy-Payload 'tools/server-update/start-web.sh' 'scripts/start-web.sh'
Copy-Payload 'tools/server-update/start-screen.sh' 'scripts/start-screen.sh'
Copy-Payload 'tools/server-update/runtime-update-apply.sh' 'runtime-update-apply.sh'

if ($ExistingFullPackage) {
    $Wheelhouse = Join-Path $ExistingFullPackage.FullName 'web-main/wheels'
    if (Test-Path -LiteralPath $Wheelhouse) { Copy-Payload $Wheelhouse.Substring($Root.Length + 1) 'web-main/wheels' }
}

# Never ship interpreter caches or generated bytecode from the developer
# machine. They are platform/version-specific and make the package noisy.
Get-ChildItem -LiteralPath $Destination -File -Recurse |
    Where-Object { $_.Extension -eq '.pyc' -or $_.FullName -match '[\\/]__pycache__[\\/]' } |
    Remove-Item -Force
Get-ChildItem -LiteralPath $Destination -Directory -Recurse |
    Where-Object { $_.Name -eq '__pycache__' } |
    Sort-Object FullName -Descending |
    Remove-Item -Force -Recurse

$required = @(
    'web-main/jar/ruoyi-admin.jar', 'web-main/jar/carbon-emission-model.jar',
    'web-screen/jar/goview.war', 'web-main/html/dist/index.html',
    'web-main/html/dist/static', 'web-main/html/carbon-model/index.html',
    'web-screen/html/dist/index.html', 'web-main/energy-engine',
    'web-main/renderer/carbon_report_agent', 'web-main/single-train-engine',
    'web-main/single-train-algorithm', 'runtime-update-apply.sh'
)
foreach ($item in $required) {
    if (-not (Test-Path -LiteralPath (Join-Path $Destination $item))) { throw "Package artifact missing: $item" }
}
if ((Get-ChildItem -LiteralPath (Join-Path $Destination 'web-main/html/dist/static') -File -Recurse).Count -lt 10) {
    throw 'Main frontend static assets are incomplete.'
}
if ((Get-ChildItem -LiteralPath (Join-Path $Destination 'web-screen/html/dist') -File -Recurse).Count -lt 3) {
    throw 'GoView frontend assets are incomplete.'
}

$Utf8 = New-Object System.Text.UTF8Encoding($false)
$Readme = @'
# Full runtime update without database changes

This package replaces application runtime files only. It contains no SQL,
database dump, user data, uploads, Redis data, GoView SQLite data, or runtime
environment secrets. The apply script verifies every file before stopping any
service, backs up application files, keeps ruoyi-db running, then restarts
ruoyi-web and ruoyi-screen and their application processes.

Required containers: ruoyi-db, ruoyi-web, ruoyi-screen. Override these names
with DB_CONTAINER, WEB_CONTAINER, and SCREEN_CONTAINER when running the script.
Upload the tar.gz and its .sha256 file in binary mode. Do not upload an
extracted or partially copied directory. Run:

```sh
bash runtime-update-apply.sh
```
'@
[IO.File]::WriteAllText((Join-Path $Destination 'SERVER-UPDATE.md'), $Readme, $Utf8)

Get-ChildItem $Destination -File -Recurse | Where-Object { $_.Extension -in @('.sh', '.md', '.txt') } | ForEach-Object {
    $Content = [IO.File]::ReadAllText($_.FullName).Replace("`r`n", "`n")
    [IO.File]::WriteAllText($_.FullName, $Content, $Utf8)
}

$Files = Get-ChildItem $Destination -File -Recurse | Sort-Object FullName
$Records = foreach ($File in $Files) {
    $Relative = $File.FullName.Substring($Destination.Length + 1).Replace('\', '/')
    "$( (Get-FileHash -LiteralPath $File.FullName -Algorithm SHA256).Hash.ToLower() )  $Relative"
}
[IO.File]::WriteAllText((Join-Path $Destination 'SHA256SUMS'), ($Records -join "`n") + "`n", $Utf8)

$ManifestLines = Get-Content -Encoding UTF8 (Join-Path $Destination 'SHA256SUMS')
if (($ManifestLines | Where-Object { $_ -notmatch '^[0-9a-f]{64}  .+$' }).Count -ne 0) {
    throw 'Generated SHA256SUMS contains malformed lines.'
}

$Archive = "$Destination.tar.gz"
& tar.exe -czf $Archive -C (Split-Path $Destination -Parent) $Name
if ($LASTEXITCODE -ne 0) { throw 'Archive creation failed.' }
$Hash = (Get-FileHash $Archive -Algorithm SHA256).Hash.ToLower()
[IO.File]::WriteAllText("$Archive.sha256", "$Hash  $Name.tar.gz`n", $Utf8)
Write-Host "PACKAGE=$Archive"
Write-Host "SHA256=$Hash"
